#!/usr/bin/env python3
"""Write a Lean file whose `#guard`s say that maps/pss.py agrees with Lean.

    python3 tests/gen_lean_pss.py > CheckPss.lean
    leanman check -C <the Lean project> CheckPss.lean

The matrices are standard pair sequences, made by pss-proof's own expansion
`PSS.oper M n` with n >= 1 (https://github.com/koteitan/pss-proof/blob/main/lean/PSS/Defs.lean),
ported as `pss.oper`. `STPS` is generated by the diagonals and `oper` with
n >= 1 (https://github.com/koteitan/pss-proof/blob/main/lean/PSS/Standard.lean), so every
matrix here is standard, and it starts at (0,0), so it is in `CTPS`.

- PAIRS: from (0,0), (0,0)(1,1), ..., (0,0)...(7,7), every result of brackets
  1..3 whose intermediate steps have length <= 10, kept at length <= 6;
  and from (0,0)(1,1)(2,2)(3,3) and the shorter diagonals, every result of
  brackets 1..3 with all steps of length <= 7.
  For each: `pairTerm M` and `pairOrdTerm M` equal the Python values.
- ONE ROW: the standard one-row sequences l of length <= 6 (from (0)(1)...(k),
  k <= 7, brackets 1..7, steps of length <= 11; that is all 84 of them).
  For each: `pairOrdTerm (withZero l)` equals the Python value and Lean `read 0 l`.
"""

import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, ROOT)

from maps import pss  # noqa: E402
from maps.bms import read  # noqa: E402
from notation import exb  # noqa: E402


def reach(starts, brackets, keep, explore):
    """Every matrix reachable from `starts` by `pss.oper` with the given
    brackets, through matrices of length <= explore; those of length <= keep."""
    seen = set()
    todo = list(starts)
    while todo:
        m = todo.pop()
        if m in seen or len(m) > explore:
            continue
        seen.add(m)
        for n in brackets:
            todo.append(pss.oper(m, n))
    return {m for m in seen if len(m) <= keep}


def pairs():
    a = reach([pss.diagSeq(0, i) for i in range(8)], range(1, 4), 6, 10)
    b = reach([pss.diagSeq(0, i) for i in range(4)], range(1, 4), 7, 7)
    return sorted(a | b, key=lambda m: (len(m), m))


def one_row():
    s = reach([tuple((j, 0) for j in range(k + 1)) for k in range(8)], range(1, 8), 6, 11)
    return sorted((tuple(a for a, _ in m) for m in s), key=lambda l: (len(l), l))


def lean_list(m):
    return '[' + ', '.join('(%d, %d)' % p for p in m) + ']'


def main():
    out = ['import Googology.Trans.BMS.ExBuchholz.PSS.Rank',
           'import Googology.Trans.BMS.common.Zero',
           '',
           'open Googology.Notation.ExBuchholz Googology.Notation.ExBuchholz.Term',
           'open Googology.Trans.PSS',
           '',
           '-- pairTerm / pairOrdTerm: Lean = Python (maps/pss.py)']
    ps = pairs()
    n = 0
    for m in ps:
        s = lean_list(m)
        out.append('#guard pairTerm %s = (%s : Term)  -- %s'
                   % (s, exb.lean(pss.pair_term(m)), exb.show(pss.pair_term(m))))
        out.append('#guard pairOrdTerm %s = (%s : Term)  -- %s'
                   % (s, exb.lean(pss.pair_ord_term(m)), exb.show(pss.pair_ord_term(m))))
        n += 2
    out += ['', '-- one row: pairOrdTerm (withZero l) = Python = read 0 l']
    rows = one_row()
    for l in rows:
        m = tuple((a, 0) for a in l)
        v = pss.pair_ord_term(m)
        if v != read(0, l):
            raise SystemExit('Python: pairOrdTerm (withZero %s) != read 0 %s' % (l, l))
        ls = '[' + ', '.join(str(a) for a in l) + ']'
        out.append('#guard pairOrdTerm (Googology.Trans.BMS.withZero %s) = (%s : Term)  -- %s'
                   % (ls, exb.lean(v), exb.show(v)))
        out.append('#guard pairOrdTerm (Googology.Trans.BMS.withZero %s) = '
                   'Googology.Trans.BMS.read 0 %s' % (ls, ls))
        n += 2
    print('\n'.join(out))
    print('-- %d pair sequences, %d one-row sequences, %d guards'
          % (len(ps), len(rows), n), file=sys.stderr)


if __name__ == '__main__':
    main()
